-- Lightweight post likes for the Terai web feed.
-- Existing posts and users are preserved; removing a post/user cleans up likes.

create table if not exists public.post_likes (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint post_likes_user_post_unique unique (user_id, post_id)
);

create index if not exists post_likes_post_id_idx
  on public.post_likes (post_id);
create index if not exists post_likes_user_id_idx
  on public.post_likes (user_id);

alter table public.post_likes enable row level security;

drop policy if exists "Authenticated users can read post likes"
  on public.post_likes;
create policy "Authenticated users can read post likes"
  on public.post_likes for select
  to authenticated
  using (true);

drop policy if exists "Users can like as themselves"
  on public.post_likes;
create policy "Users can like as themselves"
  on public.post_likes for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can remove their own likes"
  on public.post_likes;
create policy "Users can remove their own likes"
  on public.post_likes for delete
  to authenticated
  using ((select auth.uid()) = user_id);

grant select, insert, delete on public.post_likes to authenticated;
grant usage, select on sequence public.post_likes_id_seq to authenticated;

-- Returns one compact summary row per requested post. This avoids loading every
-- individual like into the browser and prevents an N+1 request per post card.
create or replace function public.get_post_like_summaries(p_post_ids bigint[])
returns table(post_id bigint, like_count bigint, liked_by_me boolean)
language sql
stable
security invoker
set search_path = public
as $$
  select
    requested.post_id,
    count(likes.id)::bigint as like_count,
    coalesce(bool_or(likes.user_id = (select auth.uid())), false) as liked_by_me
  from unnest(p_post_ids) as requested(post_id)
  left join public.post_likes as likes on likes.post_id = requested.post_id
  group by requested.post_id;
$$;

grant execute on function public.get_post_like_summaries(bigint[])
  to authenticated;

comment on table public.post_likes is
  'One lightweight appreciation reaction per user and post.';
